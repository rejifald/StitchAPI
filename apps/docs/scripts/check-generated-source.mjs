// Guard the ORDER of the generation steps in `check:types`, which is load-bearing
// and otherwise invisible.
//
// `next.config.mjs` calls `createMDX()` from `fumadocs-mdx/next`. At config-load
// time — i.e. in ANY process that loads the Next config, including `next typegen`
// — that helper fires a fire-and-forget regeneration of `.source/*.ts`:
//
//     if (process.env._FUMADOCS_MDX !== '1') {
//         process.env._FUMADOCS_MDX = '1';
//         init(isDev, core);   // async, NOT awaited, no .catch()
//     }
//
// `init()` ends in `core.emit({ write: true })`, which writes each generated file
// with a plain `fs.writeFile` — truncate-then-write, not atomic. The env guard is
// per-process, so the earlier `fumadocs-mdx` CLI step cannot suppress it.
//
// So `next typegen` exits with that write still in flight, and where the process
// death lands decides what is left on disk:
//   - before `emit()`          → files untouched            (fine)
//   - INSIDE `emit()`'s write  → `server.ts` left 0 bytes   (THE BUG)
//   - after `emit()`           → files complete             (fine)
//
// A 0-byte `.source/server.ts` has no exports, so `tsc` reports the baffling
//   lib/source.ts(3,22): error TS2306: File '.../.source/server.ts' is not a module
// plus a TS7006 cascade from the now-untyped import. The window is narrow, which
// is why this read as a flaky `verify` check: it favours cold/contended machines
// (fresh worktrees, CI runners) and hides on a warm local tree.
//
// The fix is ordering: run `next typegen` FIRST and the `fumadocs-mdx` CLI AFTER,
// so the last writer before `tsc` is the CLI — which awaits its own emit and runs
// to completion. This script asserts that invariant actually held, turning a
// future reordering into a clear failure here instead of a confusing TS2306.
//
// It deliberately asserts rather than regenerating: a regeneration would paper
// over a real ordering regression and leave the flake to resurface elsewhere.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(appRoot, '.source');

// The module `collections/server` resolves to (see tsconfig.json `paths`), and
// the one `lib/source.ts` + `lib/blog.ts` import their collections from.
const ENTRY = 'server.ts';

function fail(problem) {
    console.error(
        `check-generated-source: ${problem}\n\n` +
            `  \`.source/\` is generated by fumadocs-mdx, and \`next typegen\` rewrites it\n` +
            `  from an unawaited task in next.config.mjs's createMDX() — a non-atomic\n` +
            `  write that can leave a truncated file behind when the process exits.\n\n` +
            `  In apps/docs \`check:types\`, run \`next typegen\` BEFORE the \`fumadocs-mdx\`\n` +
            `  CLI so the CLI is the last writer before \`tsc\`. If you reordered those\n` +
            `  steps, put them back. Otherwise regenerate with \`pnpm exec fumadocs-mdx\`.`,
    );
    process.exit(1);
}

let generated;
try {
    generated = readdirSync(outDir).filter((file) => file.endsWith('.ts'));
} catch {
    fail(`\`.source/\` is missing (expected it at ${outDir})`);
}

if (!generated.includes(ENTRY)) {
    fail(`\`.source/${ENTRY}\` was never generated`);
}

// Any truncated entry is a problem, not just the one tsc resolves by path:
// tsconfig's `include` pulls every `**/*.ts` into the program, so a half-written
// `browser.ts` would surface as a syntax error rather than TS2306.
for (const file of generated) {
    if (statSync(join(outDir, file)).size === 0) {
        fail(
            `\`.source/${file}\` is empty — the generator's write was truncated`,
        );
    }
}

// `server.ts` must actually be a module. `dynamic.ts` legitimately has no
// exports, so only the entry is checked for one.
if (!/^export /m.test(readFileSync(join(outDir, ENTRY), 'utf8'))) {
    fail(`\`.source/${ENTRY}\` has no exports — \`tsc\` will report TS2306`);
}
