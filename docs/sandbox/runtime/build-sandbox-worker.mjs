#!/usr/bin/env node

/**
 * Build the playground Web Worker bundle.
 *
 * esbuild bundles `worker-main.ts` — the worker entry that wires
 * `installWorkerEntry` with the B1 `stitch-browser` build and the sandbox-sim fetch
 * shim — into ONE self-contained, Node-free ESM module the docs app serves at
 * `/sandbox/sandbox-worker.mjs` and loads via
 *   new Worker('/sandbox/sandbox-worker.mjs', { type: 'module' })
 *
 * One knob: alias `stitchapi` → packages/core/src/index.ts so the bundle resolves
 * the core source WITHOUT a build (zod is unused in the reachable graph — B1-SPIKE §1).
 *
 * No node:* or process shims are needed: core is browser-isomorphic since GAP-AUDIT §1.5
 * (PR #102). It has no static `node:*` imports and no bare `process` — it reaches
 * optional Node facilities through `globalThis.process?.getBuiltinModule('node:fs')`
 * and `globalThis.crypto`, both simply absent in a Worker (→ safe no-op defaults). The
 * old `node:crypto|fs|path` aliases and the `process` define are therefore gone; the
 * Worker's `process`/`crypto` come from `worker-main.ts` (injected as the snippet's
 * scope, where `globalThis` is shadowed — see worker-entry.ts).
 *
 * Output: apps/docs/public/sandbox/sandbox-worker.mjs (git-ignored, regenerated by
 * the docs app's `build:sandbox` script on dev/build). Override with OUT=/path.
 *
 * Usage:
 *   node docs/sandbox/runtime/build-sandbox-worker.mjs
 */
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '../../..');

const ENTRY = resolve(__dirname, 'worker-main.ts');
const OUT =
    process.env.OUT ??
    resolve(repoRoot, 'apps/docs/public/sandbox/sandbox-worker.mjs');
const CORE =
    process.env.CORE ?? resolve(repoRoot, 'packages/core/src/index.ts');

async function loadEsbuild() {
    // 1. Bare import — works if esbuild sits on a node_modules path above this
    //    script (e.g. hoisted to the workspace root).
    try {
        return await import('esbuild');
    } catch {
        /* fall through */
    }
    // 2. Resolve from the invoking package's cwd. This script lives outside any
    //    package (docs/sandbox/runtime), so a bare specifier can't see the docs
    //    app's node_modules; the app declares esbuild as a devDependency and runs
    //    this with cwd=apps/docs, so resolve esbuild explicitly from there.
    try {
        const requireFromCwd = createRequire(
            resolve(process.cwd(), 'package.json'),
        );
        return await import(
            pathToFileURL(requireFromCwd.resolve('esbuild')).href
        );
    } catch {
        /* fall through */
    }
    // 3. Explicit override: ESBUILD=/abs/path to an esbuild build.
    const fromEnv = process.env.ESBUILD;
    if (fromEnv) {
        try {
            return await import(fromEnv);
        } catch (e) {
            console.error(`Could not import ESBUILD=${fromEnv}: ${e}`);
        }
    }
    console.error(
        'esbuild not found. Run via the docs app (`pnpm --filter @stitchapi/docs ' +
            'run build:sandbox`, which declares esbuild), or set ESBUILD=/abs/path.',
    );
    process.exit(2);
}

const esbuild = await loadEsbuild();

await esbuild.build({
    entryPoints: [ENTRY],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    outfile: OUT,
    sourcemap: false,
    // Resolve `stitchapi` to the core source so the bundle builds without a publish/
    // install step. Core is browser-isomorphic (GAP-AUDIT §1.5), so no node:* or process
    // shims are required — this is the only alias the bundle needs.
    alias: {
        stitchapi: CORE,
    },
    logLevel: 'info',
});

console.log(`\n[sandbox-worker] wrote ESM Worker bundle → ${OUT}`);
